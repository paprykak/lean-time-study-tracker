describe('wyszukiwarka: zestaw zapytań z hali (wyszukiwarka2)', () => {
  const zNarzedziem = ZAPYTANIA.filter(([, s]) => s !== null) as [string, string, Zrodlo][];
  const wyniki = zNarzedziem.map(([q, s]) => ({ q, s, w: szukaj(p, q, 3).map((x) => x.wpis.s) }));

  it('zestaw ma co najmniej 200 zapytań, a oczekiwane narzędzia istnieją w rejestrze', () => {
    expect(ZAPYTANIA.length).toBeGreaterThanOrEqual(200);
    const slugi = new Set(NARZEDZIA.map((n) => n.slug));
    expect(zNarzedziem.filter(([, s]) => !slugi.has(s)).map(([q]) => q)).toEqual([]);
  });

  it('co najmniej 95% oczekiwanych narzędzi na pierwszym miejscu', () => {
    const chybione = wyniki.filter(({ s, w }) => w[0] !== s).map(({ q, s, w }) => `${q} → ${s} (jest: ${w[0] ?? 'nic'})`);
    expect(1 - chybione.length / wyniki.length, chybione.join('\n')).toBeGreaterThanOrEqual(0.95);
  });

  it('co najmniej 99% oczekiwanych narzędzi w pierwszej trójce', () => {
    const chybione = wyniki.filter(({ s, w }) => !w.includes(s)).map(({ q, s, w }) => `${q} → ${s} (jest: ${w.join(', ') || 'nic'})`);
    expect(1 - chybione.length / wyniki.length, chybione.join('\n')).toBeGreaterThanOrEqual(0.99);
  });

  it('podpowiedzi Google osobno: co najmniej 93% na pierwszym i 99% w trójce', () => {
    const g = wyniki.filter((_, i) => zNarzedziem[i][2] === 'g');
    expect(g.filter(({ s, w }) => w[0] === s).length / g.length).toBeGreaterThanOrEqual(0.93);
    expect(g.filter(({ s, w }) => w.includes(s)).length / g.length).toBeGreaterThanOrEqual(0.99);
  });
});
